import Foundation

/// One child of an app-data folder, marked by whether it can go without losing anything you made.
public struct FolderPart: Sendable, Equatable, Identifiable {
    public enum Kind: String, Sendable {
        /// Recreated by the app on its own.
        case cache = "Cache"
        /// The app sets it up again, but something saved inside is lost.
        case rebuildable = "Rebuilt on demand"
        /// Settings, history, logins: never offered for removal.
        case data = "Your data"
    }

    public let path: String
    public let name: String
    public let size: UInt64
    public let kind: Kind
    public let note: String
    /// Folders can be opened further; files can't.
    public var isFolder = true
    public var id: String { path }
    public var isRemovable: Bool { kind != .data }
}

/// Splits a big hidden folder (Claude, VS Code, ~/.cache…) into caches you can drop and data you should keep.
public enum AppDataBreakdown {
    /// Folder names Chromium and Electron apps recreate at launch.
    static let cacheNames: Set<String> = [
        "cache", "code cache", "gpucache", "dawncache", "dawngraphitecache", "dawnwebgpucache", "graphitedawncache",
        "cacheddata", "cachedextensionvsixs", "cachedprofilesdata", "shadercache", "grshadercache", "component_crx_cache",
        "crashpad", "logs", "blob_storage",
    ]
    static let cacheNote = "Recreated the next time the app runs."
    static let toolCacheNote = "Downloaded or generated by a tool, which fetches it again when it's needed."
    static let sandboxNote = "The Linux sandbox Claude uses to run code. Claude sets it up again, but files saved inside the sandbox are lost."

    /// What one child of `folder` is, from its name and where it sits.
    public static func classify(name: String, in folder: String, home: String) -> (kind: FolderPart.Kind, note: String) {
        let parent = (folder as NSString).standardizingPath
        if parent == home + "/Library/Application Support/Claude", name == "vm_bundles" { return (.rebuildable, sandboxNote) }
        if cacheNames.contains(name.lowercased()) { return (.cache, cacheNote) }
        if parent == home + "/.cache" { return (.cache, toolCacheNote) }
        if let known = ImpactKnowledge.explain(path: parent + "/" + name, home: home), known.risk == .safe {
            return (.cache, known.summary)
        }
        return (.data, "Settings, history or files the app can't recreate.")
    }

    /// The children of `folder` at or above `minimum` bytes, biggest first.
    public static func parts(of folder: String, home: String = NSHomeDirectory(), minimum: UInt64 = 10_000_000,
                             measure: (String) -> UInt64? = { DiskScanner.measure($0) }) -> [FolderPart] {
        ((try? FileManager.default.contentsOfDirectory(atPath: folder)) ?? [])
            .filter { $0 != ".DS_Store" }
            .compactMap { name -> FolderPart? in
                let path = folder + "/" + name
                let size = autoreleasepool { measure(path) ?? 0 }
                guard size >= minimum else { return nil }
                let (kind, note) = classify(name: name, in: folder, home: home)
                var isDirectory: ObjCBool = false
                let isFolder = FileManager.default.fileExists(atPath: path, isDirectory: &isDirectory) && isDirectory.boolValue
                return FolderPart(path: path, name: name, size: size, kind: kind, note: note, isFolder: isFolder)
            }
            .sorted { $0.size > $1.size }
    }

    /// Folders worth splitting: big app-data folders and the shared tool cache.
    public static func isCandidate(_ path: String, size: UInt64, home: String) -> Bool {
        if path == home + "/.cache" { return true }
        return size >= 500_000_000 && (path as NSString).deletingLastPathComponent == home + "/Library/Application Support"
    }

    /// The app that owns an Application Support folder, by the folder's name ("Claude", "Code").
    public static func owningApp(of folder: String, home: String) -> String? {
        (folder as NSString).deletingLastPathComponent == home + "/Library/Application Support" ? (folder as NSString).lastPathComponent : nil
    }
}
