import Foundation

/// Where a piece of an app's disk footprint lives.
public enum FootprintCategory: String, CaseIterable, Sendable, Hashable {
    case bundle
    case caches
    case applicationSupport
    case containers
    case preferences
    case logs
    case savedState
    case webKit

    public var title: String {
        switch self {
        case .bundle: "App"
        case .caches: "Caches"
        case .applicationSupport: "Application Support"
        case .containers: "Containers"
        case .preferences: "Preferences"
        case .logs: "Logs"
        case .savedState: "Saved State"
        case .webKit: "WebKit"
        }
    }

    /// Regenerated by the app on demand; safe to clear without losing settings or sign-ins.
    public var isCache: Bool { self == .caches }
}

public struct FootprintItem: Identifiable, Sendable, Hashable {
    public let path: String
    public let category: FootprintCategory
    /// Bytes attributed to this item alone. A container's size excludes the cache folder nested
    /// inside it, which is reported as its own `.caches` item, so totals never double count.
    public let size: UInt64

    public var id: String { path }

    public init(path: String, category: FootprintCategory, size: UInt64) {
        self.path = path
        self.category = category
        self.size = size
    }
}

public struct AppFootprint: Identifiable, Sendable, Equatable {
    public let app: InstalledApp
    public let items: [FootprintItem]

    public var id: String { app.id }

    public init(app: InstalledApp, items: [FootprintItem]) {
        self.app = app
        self.items = items
    }

    public var total: UInt64 { items.reduce(0) { $0 + $1.size } }

    /// Everything outside the app bundle: what a reset would remove.
    public var dataSize: UInt64 { items.filter { $0.category != .bundle }.reduce(0) { $0 + $1.size } }

    public var cacheSize: UInt64 { size(of: .caches) }

    public func size(of category: FootprintCategory) -> UInt64 {
        items.filter { $0.category == category }.reduce(0) { $0 + $1.size }
    }

    /// Per-category totals in display order, dropping empty categories.
    public var breakdown: [(category: FootprintCategory, size: UInt64)] {
        FootprintCategory.allCases.map { ($0, size(of: $0)) }.filter { $0.1 > 0 }
    }
}

/// Builds footprints from disk. Matching is pure (see `AppFootprintLocator`); this only measures.
public enum AppFootprintScanner {
    public static func footprint(
        for app: InstalledApp,
        home: String = NSHomeDirectory(),
        measure: (String) -> UInt64? = DiskScanner.measure
    ) -> AppFootprint {
        let located = AppFootprintLocator.locate(bundleID: app.bundleID, name: app.name, home: home)
        let raw = located.compactMap { location -> FootprintItem? in
            guard let size = measure(location.path) else { return nil }
            return FootprintItem(path: location.path, category: location.category, size: size)
        }
        let bundle = FootprintItem(path: app.path, category: .bundle, size: app.size ?? measure(app.path) ?? 0)
        return AppFootprint(app: app, items: [bundle] + attributeNested(raw))
    }

    /// Footprints for every app that may be reset, largest first. Apple apps and MacSweep itself are skipped.
    public static func scan(
        apps: [InstalledApp],
        home: String = NSHomeDirectory(),
        excludedBundleIDs: Set<String> = [],
        measure: (String) -> UInt64? = DiskScanner.measure
    ) -> [AppFootprint] {
        apps.filter { AppFootprintLocator.refusal(bundleID: $0.bundleID, excluded: excludedBundleIDs) == nil }
            .map { footprint(for: $0, home: home, measure: measure) }
            .sorted { $0.total == $1.total ? $0.app.name < $1.app.name : $0.total > $1.total }
    }

    /// Subtracts nested items from their ancestors so each byte is counted once
    /// (a container's `Data/Library/Caches` is reported as cache, not container data).
    static func attributeNested(_ items: [FootprintItem]) -> [FootprintItem] {
        let unique = Dictionary(items.map { ($0.path, $0) }, uniquingKeysWith: { first, _ in first }).values
        return unique.map { item in
            let nested = unique.filter { $0.path != item.path && PathTools.isDescendant($0.path, of: item.path) }
            let nestedSize = nested.reduce(UInt64(0)) { $0 + $1.size }
            let own = item.size > nestedSize ? item.size - nestedSize : 0
            return FootprintItem(path: item.path, category: item.category, size: own)
        }
        .sorted { $0.path < $1.path }
    }
}
